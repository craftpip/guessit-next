import { describe, it } from 'node:test';
import assert from 'node:assert';
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { categorize, classifyFile, classifyFiles } from '../src/index.js';

// ═══════════════════════════════════════════════════════════════════════════
//  TORRENT-ARCHIVE CORPUS REGRESSION — scratch/corpus-torrents.json
// ═══════════════════════════════════════════════════════════════════════════
//  Wire-in of the private torrent-archive harvest (Stream B: ~2,447 torrents
//  with full inner-file lists, ~163k files) into the persistent test suite.
//  The corpus is generated by scratch/tools/export-torrent-corpus.mjs from
//  scratch/raw/torrent-files.jsonl (byte-code paths decoded there). it is
//  gitignored and NEVER committed — this file is DATA-FREE: it only reads the
//  corpus, and anything it prints in a failure is masked (no real titles).
//
//  Three layers, per user directive (2026-09-25) — the same media inspected
//  individually AND as a whole:
//    A) every inner FILE name  → classifyFile(candidate)   — type contract
//       plus title hygiene ceilings (release junk / brackets).
//    B) every torrent NAME as a FOLDER → categorize(name)  — kind contract.
//    C) the two TOGETHER       → classifyFiles(all files of one torrent) —
//       exact one-group-per-container contract + consistency ceiling.
//
//  Budget ceilings (titleJunk, brackets, inconsistentMulti) are upper bounds
//  measured on the current dataset. They are NOT zero-tolerance: the archive
//  is a real-world backlog, and individual fixes are tracked in
//  plans/02-corpus-expansion-torrent-archive.md. A ceiling that GROWS fails —
//  a regression the suite can catch even while the backlog is actively worked.
// ───────────────────────────────────────────────────────────────────────────

const HERE = dirname(fileURLToPath(import.meta.url));
const CORPUS_PATH = join(HERE, '..', 'scratch', 'corpus-torrents.json');
const CORPUS = existsSync(CORPUS_PATH) ? JSON.parse(readFileSync(CORPUS_PATH, 'utf8')) : null;

const VALID_FILE_TYPES = ['series', 'movie', 'extra'];
const VALID_KINDS = ['collection', 'season_batch', 'episode', 'episode_collection', 'movie', 'others'];

const RELEASE_JUNK_TOKENS = [
  '1080p', '720p', '2160p', 'x265', 'hevc', 'x264', 'av1',
  'flac', 'eac3', 'aac', 'opus', 'ddp', 'dual-audio', 'dual audio',
  'bdrip', 'bluray', 'webrip', 'web-dl', 'multi-subs',
  'rlsgrp', 'fakesite',
  'repack', 'proper',
];

function releaseJunk(text) {
  const lowered = (text || '').toLowerCase();
  return RELEASE_JUNK_TOKENS.filter((t) => lowered.includes(t));
}

// Real names must never reach logs/commits: mask every alnum run ≥4 chars.
function mask(text) {
  return String(text).replace(/[A-Za-z0-9]{4,}/g, (m) => `[${m.length}]`);
}

function cand(t, f) {
  const path = String(f.path || '');
  const name = path.split('/').pop() || '';
  return {
    source_root_key: 'x',
    source_root: '/data/torrents',
    source_path: `/data/torrents/${t.name}/${path}`,
    name,
    extension: name.includes('.') ? name.slice(name.lastIndexOf('.')) : null,
    container_path: t.name,
    relative_path: path,
    file_size: (f.size ?? 0) || null, // 0-size dir entries are not fake sizes
    in_progress: false,
  };
}

function torrents() {
  return CORPUS ? CORPUS.torrents : [];
}

const SKIP = CORPUS ? false : 'scratch/corpus-torrents.json not present (generated locally, never committed)';

describe('torrent corpus — layer A: individual files classify cleanly', { skip: SKIP }, () => {
  it('corpus is non-empty', () => {
    assert.ok(CORPUS.torrents.length > 0, 'torrent corpus must not be empty');
    const files = torrents().reduce((n, t) => n + t.files.length, 0);
    assert.ok(files > 0, 'corpus must contain inner files');
  });

  it('every inner file classifies with a real type (series/movie/extra, never skip)', () => {
    const failures = [];
    let files = 0;
    for (const t of torrents()) {
      for (const f of t.files) {
        files += 1;
        const r = classifyFile(cand(t, f));
        if (!VALID_FILE_TYPES.includes(r.type)) {
          failures.push(`${mask(f.path)}: type=${r.type} (${mask(r.reason)})`);
        }
      }
    }
    assert.deepEqual(failures, [], `${failures.length}/${files} files emitted a non-file type:\n` + failures.slice(0, 30).join('\n'));
  });

  it('title hygiene stays within measured ceilings (release junk, brackets)', () => {
    const junkFails = [];
    const bracketFails = [];
    let files = 0;
    for (const t of torrents()) {
      for (const f of t.files) {
        files += 1;
        const r = classifyFile(cand(t, f));
        if (releaseJunk(r.title).length) junkFails.push(`${mask(f.path)}: title=${mask(r.title)}`);
        if (releaseJunk(r.episode_title).length) junkFails.push(`${mask(f.path)}: episode_title=${mask(r.episode_title)}`);
        if (r.title && (r.title.includes('[') || r.title.includes(']'))) bracketFails.push(`${mask(f.path)}: title=${mask(r.title)}`);
      }
    }
    assert.ok(
      junkFails.length <= 3722,
      `title junk grew to ${junkFails.length} (ceiling 3722 of ${files} files):\n` + junkFails.slice(0, 30).join('\n'),
    );
    assert.ok(
      bracketFails.length <= 2660,
      `bracketed titles grew to ${bracketFails.length} (ceiling 2660):\n` + bracketFails.slice(0, 30).join('\n'),
    );
  });
});

describe('torrent corpus — layer B: torrent names (folders) categorize cleanly', { skip: SKIP }, () => {
  it('every torrent name categorizes to one of the six kinds', () => {
    const failures = [];
    const counts = {};
    for (const t of torrents()) {
      const r = categorize(t.name);
      if (!VALID_KINDS.includes(r.kind)) failures.push(`${mask(t.name)}: kind=${r.kind}`);
      counts[r.kind] = (counts[r.kind] || 0) + 1;
    }
    assert.deepEqual(failures, [], `${failures.length}/${torrents().length} torrents had an invalid kind:\n` + failures.slice(0, 30).join('\n'));
    console.log(`  kind distribution: ${JSON.stringify(counts)}`);
  });
});

describe('torrent corpus — layer C: files and folder together (classifyFiles)', { skip: SKIP }, () => {
  it('files of one torrent yield exactly one group, keyed by the torrent name', () => {
    const failures = [];
    let torrentsChecked = 0;
    for (const t of torrents()) {
      torrentsChecked += 1;
      const batch = t.files.map((f) => cand(t, f));
      const { groups } = classifyFiles(batch);
      if (groups.length !== 1) {
        failures.push(`${mask(t.name)}: ${groups.length} groups for one torrent`);
        continue;
      }
      if (groups[0].key !== t.name) {
        failures.push(`${mask(t.name)}: group key=${mask(groups[0].key)} != torrent name`);
      }
    }
    assert.deepEqual(failures, [], `${failures.length}/${torrentsChecked} torrents did not collapse to one container group:\n` + failures.slice(0, 30).join('\n'));
  });

  it('multi-file torrents stay <= measured inconsistent ceiling', () => {
    const inconsistent = [];
    let multi = 0;
    for (const t of torrents()) {
      if (t.files.length < 2) continue;
      multi += 1;
      const batch = t.files.map((f) => cand(t, f));
      const { groups } = classifyFiles(batch);
      const g = groups[0];
      if (!g.consistent) inconsistent.push(`${mask(t.name)}: conflict=${mask((g.conflicts || []).join('; '))}`);
    }
    assert.ok(
      inconsistent.length <= 456,
      `inconsistent multi-file torrents grew to ${inconsistent.length} (ceiling 456 of ${multi}):\n` + inconsistent.slice(0, 30).join('\n'),
    );
  });
});